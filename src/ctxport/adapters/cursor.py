"""Cursor: export only.

* With --project DIR: writes DIR/.cursor/rules/ctxport.mdc, a project rule with `alwaysApply: true`
  (a file ctxport owns entirely; re-running replaces it).
* Without a project: Cursor keeps global "User Rules" in its settings UI, not in a file, so ctxport writes
  cursor-user-rules.md to paste into Cursor → Settings → Rules → User Rules.
"""
from __future__ import annotations

from pathlib import Path

from ..models import OutputFile
from ._instruction import INTRO
from ._render import render_memories_md
from .base import ExportOptions, Exporter, register

RULE_HEADER = """---
description: Background about the user (migrated by ctxport)
alwaysApply: true
---
<!-- generated by ctxport; this file is replaced on every export -->
"""


@register
class CursorExporter(Exporter):
    name = "cursor"
    label = "Cursor (project rule / User Rules)"
    appliable = True
    instructions = ("Global: paste cursor/cursor-user-rules.md into Cursor → Settings → Rules → User Rules. "
                    "Per project: re-run with --project DIR --apply to write DIR/.cursor/rules/ctxport.mdc.")

    def render(self, store, memories: list, opts: ExportOptions) -> list:
        from ._instruction import distilled_profile
        body = f"# About the user\n\n{INTRO}\n\n" + (distilled_profile(opts)
                                                       or render_memories_md(memories, redact=opts.redact, heading_level=2))
        if opts.project:
            target = Path(opts.project).expanduser() / ".cursor" / "rules" / "ctxport.mdc"
            return [OutputFile("cursor/ctxport.mdc", RULE_HEADER + body, apply_path=str(target), managed=False)]
        return [OutputFile("cursor/cursor-user-rules.md", body)]
